/**
 * Подчистка того, что отдал браузер. Распознавание русской речи спотыкается
 * на латинских терминах и англицизмах, которых в афише много: вместо «IT»
 * приходит «айти», вместо «воркшоп» — «ворк шоп». Чинится только то, что
 * встречается в наших запросах, и только целыми словами — иначе правка
 * ломает нормальный текст.
 */

const WORDS: Array<[RegExp, string]> = [
  [/\bай\s*ти\b/gi, 'IT'],
  [/\bайтишн(ый|ая|ое|ые)\b/gi, 'IT'],
  [/\bхака?\s*тон\b/gi, 'хакатон'],
  [/\bворк\s*шоп\b/gi, 'воркшоп'],
  [/\bмит\s*ап\b/gi, 'митап'],
  [/\bмиту?п\b/gi, 'митап'],
  [/\bстенд\s*ап\b/gi, 'стендап'],
  [/\bопен\s*эйр\b/gi, 'опенэйр'],
  [/\bсом+ов?\b/gi, 'сом'],
  [/\bбишкеке?к\b/gi, 'Бишкек'],
  [/\bала\s*арча\b/gi, 'Ала-Арча'],
  [/\bиссык\s*куль?\b/gi, 'Иссык-Куль'],
  [/\bчуй\s*ск(ий|ая|ом)\b/gi, 'Чуйский'],
];

export function tidySpeech(raw: string): string {
  let text = raw.replace(/\s+/g, ' ').trim();
  for (const [pattern, replacement] of WORDS) text = text.replace(pattern, replacement);
  // Браузер диктует числа цифрами, но пробел внутри них оставляет: «до 500 сом».
  text = text.replace(/(\d)\s+(\d{3})\b/g, '$1$2');
  return text ? text[0].toUpperCase() + text.slice(1) : text;
}
